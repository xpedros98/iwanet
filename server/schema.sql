-- Galaxy schema for Postgres (Supabase).
-- Run once in the Supabase dashboard: SQL Editor → New query → paste → Run.
-- Safe to run again: everything is "if not exists".

create table if not exists users (
  id         integer generated by default as identity primary key,
  username   text    not null,
  hash       text    not null,
  created_at bigint  not null default extract(epoch from now())::bigint
);
-- Case-insensitive unique usernames ("Demo" and "demo" are the same account).
create unique index if not exists users_username_lower on users (lower(username));

create table if not exists friendships (
  user_id   integer not null references users(id) on delete cascade,
  friend_id integer not null references users(id) on delete cascade,
  primary key (user_id, friend_id)
);

-- One row per user, written by the layout job (layout.ts).
-- color = friend-circle index, mapped to a palette by the client.
create table if not exists stars (
  user_id integer primary key references users(id) on delete cascade,
  x double precision not null,
  y double precision not null,
  z double precision not null,
  color integer not null,
  size  double precision not null
);

-- Small key/value table; galaxy_version increases on every layout run.
create table if not exists meta (
  key   text    primary key,
  value integer not null
);
insert into meta (key, value) values ('galaxy_version', 0) on conflict (key) do nothing;

-- Login sessions (express-session). expires = milliseconds since 1970.
create table if not exists sessions (
  sid     text   primary key,
  sess    text   not null,
  expires bigint not null
);
create index if not exists sessions_expires on sessions (expires);

-- IMPORTANT: Supabase also exposes every table in "public" through its REST API
-- using the public "anon" key. Turning on row level security with no policies
-- blocks that API completely (password hashes, sessions), while the Node server,
-- which connects as the postgres owner role, is not affected.
alter table users       enable row level security;
alter table friendships enable row level security;
alter table stars       enable row level security;
alter table meta        enable row level security;
alter table sessions    enable row level security;
